/** 阿拉伯数字 → 中文数字（1–99） */
export function cnNumber(n) {
  const D = '零一二三四五六七八九';
  n = Math.max(0, Math.floor(Number(n) || 0));
  if (n < 10) return D[n];
  const t = Math.floor(n / 10);
  const o = n % 10;
  return (t === 1 ? '' : D[t]) + '十' + (o ? D[o] : '');
}

